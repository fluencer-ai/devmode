#!/usr/bin/env python3
"""Generate references/skill-index.md: one line per skill, from its frontmatter.

Every leaf skill is hidden from the per-turn listing (disable-model-invocation),
so the orchestrator routes from this index instead: one file read, about 2k
tokens, only when a phase needs a skill. Each row names the sibling files a
skill keeps for the cases that need them.

  python3 scripts/build_skill_index.py           write the index
  python3 scripts/build_skill_index.py --check   exit 1 if the index is stale
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "references", "skill-index.md")


def description(path):
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    if not text.startswith("---"):
        return ""
    fm = text.split("---", 2)[1]
    m = re.search(r"^description:\s*(.*?)(?=^[\w-]+:|\Z)", fm, re.M | re.S)
    if not m:
        return ""
    raw = m.group(1).strip()
    if raw[:2] in (">-", "|-") or raw[:1] in (">", "|"):
        raw = raw.lstrip(">|-")
    return " ".join(raw.split()).strip("'\"")


def render(root=ROOT):
    skills = os.path.join(root, "skills")
    rows = []
    for name in sorted(os.listdir(skills)):
        sk = os.path.join(skills, name, "SKILL.md")
        if not os.path.isfile(sk):
            continue
        sib = sorted(f for f in os.listdir(os.path.join(skills, name))
                     if f.endswith(".md") and f != "SKILL.md")
        extra = f" Siblings: {', '.join(sib)}." if sib else ""
        rows.append(f"- **{name}**: {description(sk)}{extra}")
    head = [
        "# Skill index",
        "",
        "Generated by `scripts/build_skill_index.py` from each skill's frontmatter. Do not edit.",
        "",
        f"{len(rows)} skills. Open one by path: the project copy `.claude/skills/<name>/SKILL.md`,",
        "else `skills/<name>/SKILL.md` in the devmode base, else `~/.devmode/skills/<name>/SKILL.md`.",
        "Read a sibling file only when its case applies.",
        "",
    ]
    return "\n".join(head + rows) + "\n"


def main(argv):
    text = render()
    if "--check" in argv:
        try:
            with open(OUT, encoding="utf-8") as fh:
                current = fh.read()
        except FileNotFoundError:
            current = ""
        if current != text:
            print("references/skill-index.md is stale: run python3 scripts/build_skill_index.py")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
